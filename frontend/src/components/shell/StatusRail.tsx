import { useEffect, useState } from 'react'
import { FlaskConical } from 'lucide-react'
import type { Detection, LinkStatus, StreamState, Telemetry } from '@/types'
import { MISSION } from '@/lib/mockData'
import { formatZulu } from '@/lib/geo'
import { countByRisk } from '@/hooks/useDetections'
import { Badge } from '@/components/ui/Badge'

/**
 * StatusRail — the 44px band that answers "what am I looking at, and is it real?"
 *
 * The SIMULATED marker is not a debug affordance; it is a safety feature. This
 * console shows hazard positions, and every value in it is currently synthetic, so
 * the provenance sits in the most persistent piece of chrome on screen rather than
 * in a dismissible banner.
 *
 * It carries three separate verdicts, and they are deliberately not merged:
 * provenance (simulated vs real), stream currency (`StreamState`), and transport
 * health (`LinkStatus`). A single combined indicator would be shorter and would
 * hide exactly the combination an operator needs — a live picture arriving over a
 * degraded pipe.
 */
export function StatusRail({
  telemetry,
  detections,
  streamState,
  link,
}: {
  telemetry: Telemetry | null
  detections: Detection[]
  streamState: StreamState
  link: LinkStatus
}) {
  const counts = countByRisk(detections)

  return (
    <header className="flex h-status shrink-0 items-center gap-3 border-b border-rule bg-ink-deep px-3">
      {/* Wordmark: the 'shield' set apart by weight, not by a logo mark. */}
      <div className="flex shrink-0 items-baseline gap-px font-display text-title uppercase tracking-[0.16em]">
        <span className="font-bold text-paper">Aero</span>
        <span className="font-medium text-paper-dim">Shield</span>
      </div>

      <span className="hidden h-4 w-px bg-rule sm:block" aria-hidden />

      {/* Mission identity */}
      <div className="hidden min-w-0 items-baseline gap-2 sm:flex">
        <span className="font-mono text-small tracking-[0.08em] text-paper">{MISSION.name}</span>
        <span className="truncate text-small text-paper-faint">{MISSION.site}</span>
      </div>

      <div className="flex-1" />

      {/* Detection tallies — the standing count of what's out there. */}
      <div className="hidden items-center gap-1.5 md:flex">
        {counts.hazard > 0 && <Badge risk="hazard">{counts.hazard} hazard</Badge>}
        {counts.caution > 0 && <Badge risk="caution">{counts.caution} unverified</Badge>}
        {counts.cleared > 0 && <Badge risk="cleared">{counts.cleared} cleared</Badge>}
      </div>

      <StreamIndicator state={streamState} link={link} />

      {/* The provenance marker. Never hidden, never dismissible. */}
      <span
        className="flex shrink-0 items-center gap-1.5 border border-caution/50 bg-caution/10 px-1.5 py-px font-mono text-tiny uppercase tracking-[0.1em] text-caution"
        title="All telemetry, detections, and reports on screen are generated by a client-side simulator. No real sensor or model output is present."
      >
        <FlaskConical size={11} strokeWidth={2} aria-hidden />
        Simulated
      </span>

      <Clock iso={telemetry?.timestamp ?? null} />
    </header>
  )
}

/**
 * Stream health, distinct from the drone's radio link quality.
 *
 * Two glyphs, because currency and transport are two facts. The dot reports
 * `StreamState`; the mono suffix reports the pipe it arrived on, and stays silent
 * while that pipe is the healthy one so the normal case adds no noise.
 *
 * THE FALLBACK IS ANNOUNCED. A socket that gave up and left polling to carry the
 * mission is *live*, so the dot stays green and nothing looks wrong — but the
 * operator has silently lost sub-second updates, and each open tab is now spending
 * a request a second of the aircraft's ingest budget. Showing `POLL` is the whole
 * point of tracking it. Same for a reconnect: `LINK 3/5` is the difference between
 * "the radio is flaky" and "the aircraft is gone".
 */
function StreamIndicator({ state, link }: { state: StreamState; link: LinkStatus }) {
  const config: Record<StreamState, { label: string; dot: string; text: string }> = {
    live: { label: 'Stream live', dot: 'bg-cleared', text: 'text-paper-dim' },
    connecting: { label: 'Connecting', dot: 'bg-caution', text: 'text-caution' },
    stalled: { label: 'Aircraft silent', dot: 'bg-caution', text: 'text-caution' },
    unreachable: { label: 'Backend unreachable', dot: 'bg-hazard', text: 'text-hazard-lit' },
  }
  const { label, dot, text } = config[state]

  /**
   * The transport caveat, or null when there is nothing worth saying.
   *
   * Order matters: a reconnect in progress is more urgent than a completed
   * fallback, so the attempt count wins when both are true.
   */
  const transportNote =
    link.source === 'simulator'
      ? null
      : link.socketAttempts > 0
        ? `LINK ${link.socketAttempts}/5`
        : link.transport === 'polling'
          ? 'POLL'
          : null

  return (
    <span
      className={`flex shrink-0 items-center gap-1.5 font-mono text-tiny uppercase tracking-[0.1em] ${text}`}
      title={
        transportNote === null
          ? label
          : state === 'live'
            ? `${label}. The mission socket is unavailable, so position is listed once a second instead of pushed.`
            : label
      }
    >
      <span className={`h-1.5 w-1.5 ${dot}`} aria-hidden />
      <span className="hidden lg:inline">{label}</span>
      {transportNote !== null && (
        <span className="hidden border-l border-rule pl-1.5 text-paper-faint xl:inline">
          {transportNote}
        </span>
      )}
    </span>
  )
}

/**
 * Clock — mission time in Zulu, because that is what flight logs record and what
 * gets read out on radio. Falls back to local wall clock before first telemetry.
 */
function Clock({ iso }: { iso: string | null }) {
  const [now, setNow] = useState(() => new Date().toISOString())
  useEffect(() => {
    const t = setInterval(() => setNow(new Date().toISOString()), 1000)
    return () => clearInterval(t)
  }, [])

  return (
    <time
      className="shrink-0 font-mono text-small tabular text-paper"
      dateTime={iso ?? now}
    >
      {formatZulu(iso ?? now)}
    </time>
  )
}
